#!/usr/bin/env bash
# Generate a first-draft HTML mockup through the local OpenUI. See docs/factory/MOCKUPS.md.
#
#   ./.factory/scripts/mockup.sh <out.html> "<what the screen shows>"
#
# Env: OPENUI_URL   (default http://127.0.0.1:7878)
#      OPENUI_MODEL (default ollama/qwen3.5:latest; any `ollama/<name>` from `ollama list`)
#
# Mockups are product sketches for spec gate 1. Never put real claimant data in the
# description; use invented names and numbers.

set -euo pipefail

OUT="${1:-}"
shift || true
QUERY="$*"
if [ -z "$OUT" ] || [ -z "$QUERY" ]; then
  echo "usage: $0 <out.html> \"<description>\"" >&2
  exit 2
fi
case "$OUT" in *.html) ;; *) echo "error: output must be an .html file" >&2; exit 2 ;; esac
[ -e "$OUT" ] && { echo "error: $OUT exists; choose a new name" >&2; exit 2; }
command -v jq >/dev/null 2>&1 || { echo "error: jq is required" >&2; exit 2; }

URL="${OPENUI_URL:-http://127.0.0.1:7878}"
MODEL="${OPENUI_MODEL:-ollama/qwen3.5:latest}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PROMPT_FILE="$ROOT/.factory/openui/system-prompt.txt"

curl -sf -o /dev/null "$URL/" || {
  echo "error: OpenUI is not reachable at $URL; run ./.factory/scripts/openui.sh up" >&2
  exit 2
}

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# OpenUI requires a session cookie; in local mode it issues one on first request.
curl -sf -c "$work/jar" -b "$work/jar" -o /dev/null "$URL/v1/session"

# Same frontmatter instruction OpenUI's own UI appends for a new component.
frontmatter='

Always start your response with frontmatter wrapped in ---.  Set name: with a 2 to 5 word description of the component. Set emoji: with an emoji for the component, i.e.:
---
name: Fancy Button
emoji: 🎉
---

<button class="bg-blue-500 text-white p-2 rounded-lg">Click me</button>

'
jq -n --arg model "$MODEL" --rawfile sp "$PROMPT_FILE" --arg fm "$frontmatter" --arg q "$QUERY" \
  '{model: $model, temperature: 0.3, stream: true,
    messages: [{role: "system", content: ($sp + $fm)}, {role: "user", content: $q}]}' > "$work/req.json"

status="$(curl -sS -b "$work/jar" -o "$work/sse" -w '%{http_code}' \
  -H 'Content-Type: application/json' --data @"$work/req.json" "$URL/v1/chat/completions")"
[ "$status" = "200" ] || { echo "error: OpenUI returned HTTP $status:" >&2; head -c 500 "$work/sse" >&2; echo >&2; exit 1; }
if grep -q '^error:' "$work/sse"; then
  echo "error: model failed:" >&2; grep '^error:' "$work/sse" | head -3 >&2; exit 1
fi

# Join the streamed deltas, then drop thinking blocks, frontmatter and code fences.
# Models sometimes return a whole document despite the prompt; unwrap it so the
# file has one <body> (the model's body becomes a <div> that keeps its classes).
sed -n 's/^data: //p' "$work/sse" | grep -v '^\[DONE\]$' \
  | jq -rj '.choices[0].delta.content // empty' > "$work/raw"
perl -0pe '
  s/<think>.*?<\/think>\s*//gs;
  s/\A\s*---\n.*?\n---\s*\n//s;
  s/^```[a-z]*\s*$//mg;
  s/<!doctype[^>]*>//gi; s/<\/?html[^>]*>//gi;
  s{<head\b[^>]*>(.*?)</head>}{join("\n", $1 =~ m{(<style\b.*?</style>|<link\b[^>]*\bstylesheet\b[^>]*>)}gis)}gise;
  s/<body\b([^>]*)>/<div$1>/gi; s/<\/body>/<\/div>/gi;
  s{src="/icons/}{src="https://placehold.co/}g' \
  "$work/raw" > "$work/body"
grep -q '<' "$work/body" || { echo "error: model returned no HTML" >&2; head -c 500 "$work/raw" >&2; echo >&2; exit 1; }

mkdir -p "$(dirname "$OUT")"
{
  cat <<'EOF'
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<!-- Draft mockup generated by OpenUI (wandb/openui) via .factory/scripts/mockup.sh. Not product code. -->
<script src="https://cdn.tailwindcss.com?plugins=forms,typography"></script>
<script>
tailwind.config = { darkMode: ['class'], theme: { extend: { colors: {
  border: 'hsl(var(--border))', input: 'hsl(var(--input))', ring: 'hsl(var(--ring))',
  background: 'hsl(var(--background))', foreground: 'hsl(var(--foreground))',
  primary: { DEFAULT: 'hsl(var(--primary))', foreground: 'hsl(var(--primary-foreground))' },
  secondary: { DEFAULT: 'hsl(var(--secondary))', foreground: 'hsl(var(--secondary-foreground))' },
  destructive: { DEFAULT: 'hsl(var(--destructive))', foreground: 'hsl(var(--destructive-foreground))' },
  muted: { DEFAULT: 'hsl(var(--muted))', foreground: 'hsl(var(--muted-foreground))' },
  accent: { DEFAULT: 'hsl(var(--accent))', foreground: 'hsl(var(--accent-foreground))' },
  popover: { DEFAULT: 'hsl(var(--popover))', foreground: 'hsl(var(--popover-foreground))' },
  card: { DEFAULT: 'hsl(var(--card))', foreground: 'hsl(var(--card-foreground))' } } } } };
</script>
<style type="text/tailwindcss">
@layer base { :root {
  --background: 0 0% 100%; --foreground: 240 10% 3.9%;
  --card: 0 0% 100%; --card-foreground: 240 10% 3.9%;
  --popover: 0 0% 100%; --popover-foreground: 240 10% 3.9%;
  --primary: 240 5.9% 10%; --primary-foreground: 0 0% 98%;
  --secondary: 240 4.8% 95.9%; --secondary-foreground: 240 5.9% 10%;
  --muted: 240 4.8% 95.9%; --muted-foreground: 240 3.8% 46.1%;
  --accent: 240 4.8% 95.9%; --accent-foreground: 240 5.9% 10%;
  --destructive: 0 84.2% 60.2%; --destructive-foreground: 0 0% 98%;
  --border: 240 5.9% 90%; --input: 240 5.9% 90%; --ring: 240 5.9% 10%;
} }
</style>
</head>
<body class="bg-background text-foreground">
EOF
  cat "$work/body"
  printf '\n</body>\n</html>\n'
} > "$OUT"

echo "mockup written: $OUT"
